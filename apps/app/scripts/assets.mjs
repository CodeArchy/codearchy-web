#!/usr/bin/env node
/**
 * Copies what the in-browser engine loads at run time into
 * public/engine/<version>/ (git-ignored), and writes src/generated/engine.ts:
 *
 *   parsers/*.wasm      the pinned tree-sitter grammars + web-tree-sitter.wasm
 *   sqlite3.wasm        SQLite WASM (the index, on OPFS)
 *   elk-worker.js       ELK (the Map's layout, in a worker)
 *   samples/polyglot.json   fixtures/polyglot, for "Try the sample"
 *
 * <version> is a hash of the files, so the service worker can cache them
 * forever and a new engine never mixes with an old one.
 */
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import { createRequire } from 'node:module';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(APP, 'package.json'));
const pkgDir = (name) => path.dirname(require.resolve(`${name}/package.json`));

const grammars = pkgDir('@codearchy/grammars');
const manifest = JSON.parse(fs.readFileSync(path.join(grammars, 'grammars.json'), 'utf8'));
const files = new Map(); // published path → source path
for (const g of manifest.grammars) for (const f of g.files) files.set(`parsers/${f}`, path.join(grammars, 'wasm', f));
const treesitter = pkgDir('@codearchy/treesitter');
files.set('parsers/web-tree-sitter.wasm', createRequire(path.join(treesitter, 'package.json')).resolve('web-tree-sitter/web-tree-sitter.wasm'));
files.set('sqlite3.wasm', require.resolve('@sqlite.org/sqlite-wasm/sqlite3.wasm'));
files.set('elk-worker.js', require.resolve('elkjs/lib/elk-worker.min.js'));
for (const [, src] of files) if (!fs.existsSync(src)) throw new Error(`missing ${src}: run \`pnpm codearchy:build\` first`);

// The sample: fixtures/polyglot from the codearchy checkout.
const fixture = path.resolve(APP, '..', '..', '.codearchy', 'fixtures', 'polyglot');
const sample = {};
const walk = (dir, rel) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        const r = rel ? `${rel}/${e.name}` : e.name;
        if (e.isDirectory()) walk(path.join(dir, e.name), r);
        else sample[r] = fs.readFileSync(path.join(dir, e.name), 'utf8');
    }
};
walk(fixture, '');
const sampleJson = JSON.stringify(sample);

const hash = createHash('sha256');
for (const [rel, src] of [...files].sort()) hash.update(rel).update(fs.readFileSync(src));
hash.update(sampleJson);
const version = hash.digest('hex').slice(0, 12);

const root = path.join(APP, 'public', 'engine');
fs.rmSync(root, { recursive: true, force: true });
const out = path.join(root, version);
for (const [rel, src] of files) {
    fs.mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
    fs.copyFileSync(src, path.join(out, rel));
}
fs.mkdirSync(path.join(out, 'samples'), { recursive: true });
fs.writeFileSync(path.join(out, 'samples', 'polyglot.json'), sampleJson);

fs.mkdirSync(path.join(APP, 'src', 'generated'), { recursive: true });
fs.writeFileSync(
    path.join(APP, 'src', 'generated', 'engine.ts'),
    `// Generated by scripts/assets.mjs: do not edit.\nexport const ENGINE_BASE = '/engine/${version}/';\n`
);
// Whether this build serves the narration voice (scripts/voice-model.mjs ran first, as in Docker):
// decided here, so the app never asks the server for a file it doesn't have.
const voice = JSON.parse(fs.readFileSync(path.join(APP, 'src', 'voice', 'model.json'), 'utf8'));
const voiceDir = path.join(APP, 'public', 'voice', voice.revision.slice(0, 8));
const voiceServed = Object.entries(voice.files).every(([rel, f]) => fs.existsSync(path.join(voiceDir, rel)) && fs.statSync(path.join(voiceDir, rel)).size === f.size) && fs.existsSync(path.join(APP, 'public', 'voice', 'ort', 'ort-wasm-simd-threaded.jsep.wasm'));
fs.writeFileSync(
    path.join(APP, 'src', 'generated', 'voice.ts'),
    `// Generated by scripts/assets.mjs: do not edit.\nexport const VOICE_SERVED = ${voiceServed};\n`
);
const grammarCount = [...files.keys()].filter((k) => k.startsWith('parsers/tree-sitter-')).length;
console.log(`[assets] public/engine/${version}/: ${grammarCount} grammars, web-tree-sitter.wasm, sqlite3.wasm, elk-worker.js, sample; voice ${voiceServed ? 'served' : 'not served (pnpm voice)'}`);
